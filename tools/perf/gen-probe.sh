#!/usr/bin/env bash
# Writes the page probe into a Dart constant, so that PDA_PERF builds can inject it.
#   tools/perf/gen-probe.sh
# Run it after each change to pda-perf-probe.user.js, and commit both files.
# Builds without PDA_PERF do not reference the constant, so it is not in their code.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
src="$here/pda-perf-probe.user.js"
out="$here/../../lib/utils/perf/probe_source.g.dart"
if grep -q "'''" "$src"; then
  echo "The probe contains ''', which ends a Dart raw string. Remove it first." >&2
  exit 1
fi
{
  echo "// GENERATED by tools/perf/gen-probe.sh from tools/perf/pda-perf-probe.user.js. Do not edit."
  echo "// ignore_for_file: prefer_single_quotes"
  echo
  echo "const String perfProbeSource = r'''"
  cat "$src"
  echo "''';"
} >"$out"
echo "Wrote $out"
